/* Поиск справочника: без ИИ. Вопрос разбивается на слова, слова приводятся к основе, ищутся в частых вопросах
   и в пунктах документов (BM25). Ответ — всегда дословный текст пунктов, ничего не сочиняется. */
function makeEngine(D){
  "use strict";
  var LAT={a:'а',c:'с',e:'е',o:'о',p:'р',x:'х',y:'у',k:'к',m:'м',t:'т',h:'н',b:'в'};
  function norm(s){
    return String(s||'').toLowerCase().replace(/ё/g,'е').replace(/[a-zа-я0-9]+/g,function(w){
      // OCR в PDF: «OПOП» — латинские буквы вперемешку с русскими
      return /[а-я]/.test(w)&&/[a-z]/.test(w)?w.replace(/[a-z]/g,function(c){return LAT[c]||c;}):w;});
  }
  var STOP={};('и в во на с со по к ко о об от до за из у а но ли же бы что как это мне меня я ты мы вы он она они мой моя мое мои мою твой '+
    'его ее их там тут или если то для при ну есть был была были будет быть так уже еще ещё только очень а то ли ведь вот какой какая какие '+
    'кто где когда зачем почему чем чего кого кому сам сама себя свой свою свои всё все весь можно нужно надо ли бывает делать сделать '+
    'хочу хотел хотела могу может могут ли ли').split(' ').forEach(function(w){STOP[w]=1;});
  var END=['иями','ями','ами','ией','ого','его','ому','ему','ыми','ими','ость','ости','ться','тся','ешь','ете','ите','ает','яет','ует','ают','яют','уют',
    'ала','ила','ыла','ела','али','или','ыли','ели','ать','ять','ить','еть','уть','ыть','ая','яя','ое','ее','ые','ие','ый','ий','ой','ей','ом','ем','ам','ям',
    'ах','ях','ов','ев','ую','юю','ия','ья','ии','ью','ал','ил','ыл','ел','ла','ли','ло','ть','ти','ет','ит','ют','ут','ат','ят','ся','сь',
    'а','я','о','е','ы','и','у','ю','ь','й','л'];
  function stem(w){
    if(w.length<=3||/^\d/.test(w))return w;
    for(var i=0;i<END.length;i++){var e=END[i];if(w.length-e.length>=3&&w.slice(-e.length)===e){w=w.slice(0,-e.length);break;}}
    return w.length>7?w.slice(0,7):w;
  }
  // разговорное → как в документах
  var SYN={'стипуха':'стипендия','стипуху':'стипендия','стипухи':'стипендия','стипа':'стипендия','стипу':'стипендия','стипы':'стипендия','общага':'общежитие','общаги':'общежитие','общагу':'общежитие','общаге':'общежитие',
    'академ':'академический отпуск','академа':'академический отпуск','академе':'академический отпуск','академку':'академический отпуск',
    'хвост':'академическая задолженность','хвосты':'академическая задолженность','хвостов':'академическая задолженность','хвостами':'академическая задолженность',
    'долг':'академическая задолженность','долги':'академическая задолженность','долгов':'академическая задолженность','долгами':'академическая задолженность',
    'автомат':'автомат зачет текущего контроля','автоматом':'автомат зачет текущего контроля','матпомощь':'материальная поддержка','матпомощи':'материальная поддержка',
    'пгас':'повышенная академическая стипендия','повышенка':'повышенная стипендия','повышенку':'повышенная стипендия','неуд':'неудовлетворительно','незачет':'не зачтено',
    'тройка':'удовлетворительно','тройку':'удовлетворительно','тройки':'удовлетворительно','двойка':'неудовлетворительно','двойку':'неудовлетворительно','двойки':'неудовлетворительно','пара':'занятие','пары':'занятие','пару':'занятие','пар':'занятие',
    'прогулял':'неявка','прогул':'неявка','проспал':'неявка','пропустил':'неявка пропуск','больничный':'болезнь справка','заболел':'болезнь','болел':'болезнь','болею':'болезнь',
    'вуз':'университет организацию','шпора':'шпаргалка источники информации','шпоры':'шпаргалка источники информации','списал':'списывание','списать':'списывание','телефон':'телефон технических средств',
    'выгонят':'отчисление','выгнали':'отчисление','отчислят':'отчисление','отчислили':'отчисление','уйти':'отчисление собственному желанию','забрать':'отчисление',
    'платник':'платной основе договор','платники':'платной основе договор','бюджет':'бюджетных бюджет','физра':'физкультура физической культурой','физры':'физкультура','физру':'физкультура',
    'препод':'преподаватель','деканат':'директорат','деканате':'директорат','деканата':'директорат','декан':'директор','учебный':'учебный','кушать':'еду','поесть':'еду','преподу':'преподаватель','препода':'преподаватель','зачетка':'зачетная книжка','зачетку':'зачетная книжка','зачетке':'зачетная книжка','сессия':'сессия промежуточная аттестация',
    'сессию':'сессия промежуточная аттестация','сессии':'сессия промежуточная аттестация','экзамен':'экзамен','зачет':'зачет','пересдача':'пересдача повторная','пересдать':'пересдать повторная','пересдачи':'пересдачи повторная',
    'куртка':'верхней одежде','куртке':'верхней одежде','курить':'курить курение','вейп':'курить курение','бухать':'алкогольные','пиво':'алкогольные','пропуск':'пропуск','студак':'студенческий билет'};
  function words(s){var all=norm(s).match(/[a-zа-я0-9]+/g)||[],out=[];
    all.forEach(function(w,i){
      // «можно ли есть на паре» — это про еду, а «есть ли» — служебное
      if(w==='есть'&&all[i+1]!=='ли'&&(i>0&&/^(можно|ли|нельзя|разрешено)$/.test(all[i-1])))w='еду';
      if(!STOP[w])out.push(w);});
    return out;}
  function terms(s){return words(s).map(stem);}
  function qterms(s){
    var out=[],seen={};
    words(s).forEach(function(w){
      var group=[stem(w)];if(SYN[w])terms(SYN[w]).forEach(function(t){if(group.indexOf(t)<0)group.push(t);});
      var key=group[0];if(seen[key])return;seen[key]=1;out.push(group);
    });
    return out;
  }
  // индекс: частые вопросы и пункты
  function Index(items){
    var N=items.length,df={},len=0,docs=items.map(function(it){var tf={},n=0;
      it.f.forEach(function(f){terms(f[0]).forEach(function(t){tf[t]=(tf[t]||0)+f[1];n+=f[1];});});
      Object.keys(tf).forEach(function(t){df[t]=(df[t]||0)+1;});len+=n;return {tf:tf,n:n};});
    var avg=len/Math.max(1,N),vocab=Object.keys(df);
    var idf={};vocab.forEach(function(t){idf[t]=Math.log(1+(N-df[t]+.5)/(df[t]+.5));});
    var pre={};
    function expand(q){ // основа из вопроса → основы в индексе (совпадение или общий префикс)
      if(pre[q])return pre[q];var r=[];
      vocab.forEach(function(t){if(t===q)r.push([t,1]);else if(q.length>=4&&t.length>=4&&(t.indexOf(q)===0||q.indexOf(t)===0))r.push([t,.75]);});
      return pre[q]=r;
    }
    return {gidf:function(groups){ // насколько редкое (значимое) каждое слово вопроса
      return groups.map(function(g){var m=0;g.forEach(function(qt){expand(qt).forEach(function(e){if(idf[e[0]]>m)m=idf[e[0]];});});return m;});},
    score:function(groups){
      var res=docs.map(function(){return {s:0,hit:0,mask:0};});
      groups.forEach(function(g,gi0){
        var best=docs.map(function(){return 0;});
        g.forEach(function(qt,gi){expand(qt).forEach(function(e){var t=e[0],w=e[1]*(gi?0.8:1),id=idf[t];
          docs.forEach(function(d,i){var f=d.tf[t];if(!f)return;var v=id*w*f*2.2/(f+1.2*(.25+.75*d.n/avg));if(v>best[i])best[i]=v;});});});
        best.forEach(function(v,i){if(v>0){res[i].s+=v;res[i].hit++;res[i].mask|=1<<gi0;}});
      });
      return res;
    }};
  }
  var CH={};D.chunks.forEach(function(c){CH[c.i]=c;});
  var cardIdx=Index(D.cards.map(function(c){
    var f=[[c.q,3],[c.k,2]];c.r.forEach(function(r){var ch=CH[r[0]];if(ch)f.push([ch.t,.3]);});return {f:f};}));
  // покрытие считаем только по самому вопросу и ключевым словам: так «справка об обучении» не уедет в «справку для физкультуры»
  var cardQK=Index(D.cards.map(function(c){return {f:[[c.q,1],[c.k,1]]};}));
  var chIdx=Index(D.chunks.map(function(c){return {f:[[c.t,1],[c.s||'',.5]]};}));
  function ask(text){
    var g=qterms(text);if(!g.length)return {groups:g,cards:[],chunks:[]};
    var qk=cardQK.score(g);
    var cs=cardIdx.score(g).map(function(r,i){return {i:i,s:r.s,cov:qk[i].hit/g.length};}).filter(function(x){return x.s>0;}).sort(function(a,b){return b.s-a.s;});
    // пункт засчитываем, только если в нём есть самое редкое слово вопроса («справку» в «как получить справку об обучении»)
    var sc=chIdx.score(g),cnt=g.map(function(_,gi){var n=0;sc.forEach(function(r){if(r.mask&(1<<gi))n++;});return n;}),key=-1;
    cnt.forEach(function(n,gi){if(n>0&&(key<0||n<cnt[key]))key=gi;});
    var ks=sc.map(function(r,i){return {i:i,s:r.s,cov:r.hit/g.length,key:key>=0&&!!(r.mask&(1<<key))};}).filter(function(x){return x.s>0;}).sort(function(a,b){return b.s-a.s;});
    return {groups:g,cards:cs,chunks:ks};
  }
  return {ask:ask,norm:norm,stem:stem,qterms:qterms,words:words};
}
if(typeof module!=='undefined')module.exports=makeEngine;
