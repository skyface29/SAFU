// Тесты склейки строк из PDF, шапки работы и строки вида работы (без браузера).
// Запуск: node site/antiplagiat/tests/lines.test.js
require('../format.js');
const { continuesLine, unwrapText, docHeader, kindOfLine } = global.Formatter;
let fail = 0, n = 0;
const eq = (name, got, want) => { n++; const g = JSON.stringify(got), w = JSON.stringify(want); if (g !== w) { fail++; console.log('✗', name, '\n   получили:', g, '\n   ожидали: ', w); } };

/* continuesLine: [a, b, ожидание] */
const C = [
  ['в области информационной', 'безопасности России', 'space'],                          // строчная после строки без точки
  ['«О стандартизации в Российской', 'Федерации» (ст. 2)', 'space'],                    // незакрытая кавычка
  ['ГОСТ «Методы и средства. Системы менеджмента безопасности.', 'Требования».', 'space'],         // точка внутри открытой кавычки
  ['сайты ФСТЭК России (fstec.ru), ФСБ России (fsb.ru, Банка', 'России (cbr.ru)', 'space'], // незакрытая скобка
  ['из списка литературы', '(кроме закона № 162-ФЗ).', 'space'],                        // скобка со строчной
  ['электронной цифровой подписи»', '(стандарт ФСБ России)', 'space'],
  ['инфор-', 'мации', 'hyphen'],                                                         // перенос слова
  ['Работа выполнена.', 'Далее текст', false],                                           // конец фразы
  ['Задачи работы:', 'изучить источники;', false],                                       // двоеточие — дальше перечисление
  ['Введение', 'Актуальность темы', false],                                              // заголовок и текст с заглавной
  ['3.1. Повторить материалы лекции', '3.2. Ознакомиться с литературой', false],         // следующий пункт
  ['Список задач', '- первая задача', false],                                            // маркер списка
  ['Варианты ответа', 'а) первый вариант', false],                                       // буква со скобкой
  ['федеральное государственное автономное образовательное учреждение', 'высшего образования', false],   // шапка титула
  ['ПРИЛОЖЕНИЕ А', '(обязательное)', false],                                             // подпись приложения
  ['Рисунок 1 – Схема сети', 'Таблица 1 – Данные', false],
  ['', 'текст', false], ['текст', '', false],
  ['Метод — средство', 'достижения цели', 'space'],
  ['Пример - ', 'текст', 'space'],                                                       // дефис после пробела — не перенос
];
for (const [a, b, want] of C) eq('continuesLine(' + a + ' | ' + b + ')', continuesLine(a, b), want);

/* unwrapText */
eq('unwrap: методичка', unwrapText(['2.1. Федеральный закон «О стандартизации в Российской', 'Федерации» (ст. 2).', '2.2. ГОСТ Р 34.10-2012']),
  ['2.1. Федеральный закон «О стандартизации в Российской Федерации» (ст. 2).', '2.2. ГОСТ Р 34.10-2012']);
eq('unwrap: перенос', unwrapText(['защита инфор-', 'мации']), ['защита информации']);
eq('unwrap: пустые строки выпадают', unwrapText(['а', '', '  ', 'Б.']), ['а', 'Б.']);
eq('unwrap: три строки подряд', unwrapText(['сформировать у обучающихся', 'целостное представление о', 'системе стандартов.']), ['сформировать у обучающихся целостное представление о системе стандартов.']);
eq('unwrap: идемпотентно', unwrapText(unwrapText(['а б', 'в г.', 'Д е'])), unwrapText(['а б', 'в г.', 'Д е']));

/* kindOfLine */
const K = [
  ['Практическая работа №10', 'prakt'], ['ПРАКТИЧЕСКАЯ РАБОТА № 3', 'prakt'], ['Практическое занятие 4', 'prakt'],
  ['Лабораторная работа № 2', 'laba'], ['ЛАБОРАТОРНАЯ РАБОТА', 'laba'], ['Отчёт по лабораторной работе №1', 'laba'], ['Отчет о лабораторной работе', 'laba'],
  ['Отчёт по практической работе № 5', 'prakt'], ['Контрольная работа', 'kontrol'], ['КУРСОВАЯ РАБОТА', 'kursovaya'], ['Курсовой проект', 'kproekt'],
  ['РЕФЕРАТ', 'referat'], ['Эссе', 'esse'], ['ДОКЛАД', 'doklad'], ['Расчётно-графическая работа', 'rgr'],
  ['ОТЧЕТ о прохождении учебной практики', 'praktika'], ['ОТЧЕТ О НАУЧНО-ИССЛЕДОВАТЕЛЬСКОЙ РАБОТЕ', 'nir'],
  ['ВЫПУСКНАЯ КВАЛИФИКАЦИОННАЯ РАБОТА', 'vkr'], ['Магистерская диссертация', 'magistr'], ['Дипломный проект', 'specialist'],
  ['Рефераты студентов проверяются преподавателем каждую неделю по вторникам и четвергам в течение семестра', null],   // длинная фраза
  ['Введение', null], ['Цель работы', null], ['Контрольные вопросы', null],
];
for (const [l, want] of K) eq('kindOfLine(' + l + ')', kindOfLine(l), want);

/* docHeader */
eq('шапка методички', docHeader(['Практическая работа №10', 'Рассмотрение государственной политики в области информационной', 'безопасности', '1. Цель работы: сформировать']),
  { kind: 'prakt', num: '10', topic: 'Рассмотрение государственной политики в области информационной безопасности', head: 2 });
eq('шапка без темы', docHeader(['Лабораторная работа № 3', 'Цель работы: изучить делитель напряжения.']), { kind: 'laba', num: '3', topic: '', head: 1 });
eq('тема с «Тема:»', docHeader(['ЛАБОРАТОРНАЯ РАБОТА №2', 'Тема: «Шифр Цезаря»', 'Цель работы: …']), { kind: 'laba', num: '2', topic: 'Шифр Цезаря', head: 2 });
eq('номер без №', docHeader(['Практическая работа 7', 'Сети']), { kind: 'prakt', num: '7', topic: 'Сети', head: 2 });
eq('титульный лист — не шапка', docHeader(['МИНИСТЕРСТВО НАУКИ И ВЫСШЕГО ОБРАЗОВАНИЯ', 'РЕФЕРАТ', 'на тему']), null);
eq('обычный текст — не шапка', docHeader(['Введение', 'Актуальность темы.']), null);
eq('вид глубоко в тексте — не шапка', docHeader(['Первый абзац.', 'Второй абзац.', 'Третий абзац.', 'Четвёртый абзац.', 'Практическая работа №1']), null);
eq('дисциплина в шапке', docHeader(['Практическая работа №2', 'по дисциплине «Криптография»', 'Цель работы: …']).discipline, 'Криптография');
eq('шапка: дальше сразу пункт', docHeader(['Практическая работа №5', '1. Задание: …']).topic, '');

console.log(fail ? `ПРОВАЛ: ${fail} из ${n}` : `${n} из ${n} проверок пройдено`);
process.exit(fail ? 1 : 0);
