// Тесты приведения библиографических записей (normBib) к образцам приложения М СТО САФУ.
// Запуск: node site/antiplagiat/tests/bib.test.js
require('../format.js');
const { normBib } = global.Formatter;
let fail = 0, n = 0;
const eq = (name, got, want) => { n++; if (got !== want) { fail++; console.log('✗', name, '\n   получили:', JSON.stringify(got), '\n   ожидали: ', JSON.stringify(want)); } };
const ok = (name, cond, info) => { n++; if (!cond) { fail++; console.log('✗', name, info ? JSON.stringify(info) : ''); } };

/* 1. точные ожидания */
const T = [
  ['Иванов И.И. Основы защиты информации. - М.: Юрайт, 2020. - 300 стр.', 'Иванов, И. И. Основы защиты информации / И. И. Иванов. – Москва: Юрайт, 2020. – 300 с.'],
  ['Петров, П. П. Безопасность сетей : учебник / П. П. Петров. – СПб. : Питер, 2019. – 412 с.', 'Петров, П. П. Безопасность сетей: учебник / П. П. Петров. – Санкт-Петербург: Питер, 2019. – 412 с.'],
  ['Очерки истории Поморья. – С.-Петерб.: Изд-во С.-Петерб. ун-та, 2010. – 312 с.', 'Очерки истории Поморья. – Санкт-Петербург: Изд-во С.-Петерб. ун-та, 2010. – 312 с.'],
  ['Булыгин, Ю. С. Архангельск в эпоху Петра // Вопросы истории. – 2012. – № 4. – С. 45-60.', 'Булыгин, Ю. С. Архангельск в эпоху Петра / Ю. С. Булыгин // Вопросы истории. – 2012. – № 4. – С. 45–60.'],
  ['Сборник. – М.-Л.: Наука, 1950. – 200 с.', 'Сборник. – М.-Л.: Наука, 1950. – 200 с.'],
  ['Иванов И.И., Петров П.П., Сидоров С.С., Кузнецов К.К. Большая книга. - М.: Наука, 2020. - 500 с.', 'Большая книга / И. И. Иванов, П. П. Петров, С. С. Сидоров, К. К. Кузнецов. – Москва: Наука, 2020. – 500 с.'],
  ['Иванов И.И. Сайт [Электронный ресурс]. URL: https://a.ru/b. (дата обращения 1.2.2024)', 'Иванов, И. И. Сайт / И. И. Иванов. – URL: https://a.ru/b (дата обращения: 01.02.2024).'],
  ['Иванов И.И. Книга. М., 2020. 300 с.', 'Иванов, И. И. Книга. М., 2020. 300 с.'],
  ['Иванов И.И. Книга / И.И. Иванов. - М.: Наука, 2020. - 300 с.', 'Иванов, И. И. Книга / И. И. Иванов. – Москва: Наука, 2020. – 300 с.'],
  ['Кузнецова М.В., Сидоров А.А. Сети. - М.: Юрайт, 2020. - 300 с.', 'Кузнецова, М. В. Сети / М. В. Кузнецова, А. А. Сидоров. – Москва: Юрайт, 2020. – 300 с.'],
  ['Тест. - Ростов н/Д: Феникс, 2018. - 50 с.', 'Тест. – Ростов-на-Дону: Феникс, 2018. – 50 с.'],
  ['Иванов И.И. Статья // Журнал. 2020. Т. 5, № 2. С. 3-9.', 'Иванов, И. И. Статья / И. И. Иванов // Журнал. – 2020. – Т. 5, № 2. – С. 3–9.'],
  ['Справка. – URL: https://site.ru/a//b?q=1 (дата обращения: 05.05.2025).', 'Справка. – URL: https://site.ru/a//b?q=1 (дата обращения: 05.05.2025).'],
];
for (const [a, b] of T) eq('образец: ' + a.slice(0, 40), normBib(a), b);

/* 2. свойства на большом наборе «грязных» записей */
const authors = ['Иванов И.И.', 'Иванов И. И.', 'Иванов, И. И.', 'Иванов-Петров А.Б.', "O'Neil J.", 'Smith J. A.', 'Кузнецова М.В., Сидоров А.А.', 'Ли В.', ''];
const titles = ['Основы защиты информации', 'Безопасность сетей : учебник', '«Цифровая экономика» и право', 'C++ для начинающих', 'Изд-во и т.д.: сборник', 'История С.-Петербурга'];
const places = ['М.', 'М.:', 'СПб.', 'С.-Пб.', 'С.-Петерб.', 'Ростов н/Д', 'Москва', 'Архангельск', 'М.-Л.', 'London', 'Н. Новгород'];
const pubs = ['Юрайт', 'Питер', 'Изд-во САФУ', 'Изд-во С.-Петерб. ун-та', 'Наука', 'Springer'];
const tails = [' - 300 с.', ' - 300 стр.', '. – 120 p.', ' – С. 10-20.', '', ' – ISBN 978-5-534-01234-5.', ' – URL: https://example.org/a-b_c?x=1&y=2 (дата обращения: 01.10.2025).', ' [Электронный ресурс]. – Режим доступа: http://site.ru/page.html', ' // Вестник САФУ. 2021. №3. С. 10-20.'];
const pick = (a, i) => a[i % a.length];
let k = 0;
for (let i = 0; i < 1600; i++) {
  const src = (pick(authors, i) ? pick(authors, i) + ' ' : '') + pick(titles, i * 7 + 1) + '. - ' + pick(places, i * 3 + 2) + (pick(places, i * 3 + 2).endsWith(':') ? ' ' : ': ') + pick(pubs, i * 5) + ', ' + (1990 + i % 35) + '.' + pick(tails, i * 11 + 3);
  const out = normBib(src);
  k++;
  ok('идемпотентность: ' + src, normBib(out) === out, [src, out, normBib(out)]);
  ok('нет «..» и « ,»: ' + src, !/\.\.(?!\.)| ,| \./.test(out.replace(/https?:\S+/g, '')), out);
  ok('дефис в сокращениях цел: ' + src, !/(С\. – Петерб|Изд – во|ун – та|М\. – Л\.)/.test(out), out);
  for (const u of src.match(/https?:\/\/[^\s)]+/g) || []) ok('ссылка не испорчена: ' + u, out.includes(u.replace(/[.,;]+$/, '')), out);
  ok('год сохранён: ' + src, out.includes(String(1990 + i % 35)), out);
  ok('точка в конце', /\.$/.test(out), out);
  ok('нет двойных пробелов', !/ {2}/.test(out), out);
}
console.log(`${n - fail} из ${n} проверок пройдено (${k} сгенерированных записей)`);
process.exit(fail ? 1 : 0);
