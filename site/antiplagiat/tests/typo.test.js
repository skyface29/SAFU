// Тесты неразрывных пробелов (п. 4.1.14 СТО САФУ). «_» в ожиданиях означает неразрывный пробел.
// Запуск: node site/antiplagiat/tests/typo.test.js
require('../format.js');
const nbsp = global.Formatter._nbsp;
let fail = 0, n = 0;
const T = [
  ['Иванов И. И. пишет', 'Иванов_И._И. пишет'],
  ['В. В. Иванов', 'В._В._Иванов'],
  ['по данным А.С. Пушкина', 'по данным А.С._Пушкина'],
  ['Иванов И.И., Петров', 'Иванов_И.И., Петров'],
  ['см. рис. 1 и т.д.', 'см. рис._1 и т._д.'],
  ['и т. д. Далее текст', 'и т._д. Далее текст'],          // после «т. д.» новое предложение: обычный пробел
  ['и т. д. Далее', 'и т._д. Далее'],                  // повторное оформление ничего не меняет
  ['в 2020 г. Анализ показал', 'в 2020_г. Анализ показал'], // «г.» после года не цепляется к следующему слову
  ['г. Москва', 'г._Москва'],
  ['300 с. Далее', '300_с. Далее'],
  ['С. 25', 'С._25'],
  ['№ 5 и § 3', '№_5 и §_3'],
  ['100 руб. и 5 кг', '100_руб. и 5_кг'],
  ['т. е. так', 'т._е. так'],
  ['ISBN 978-5-02-012345-6', 'ISBN_978-5-02-012345-6'],
  ['Метод – средство', 'Метод_– средство'],
  ['США. Это', 'США. Это'],
  ['Т. 5, вып. 2', 'Т._5, вып. 2'],
  ['Сидоров, А. А. Криптография / А. А. Сидоров', 'Сидоров, А._А. Криптография / А._А._Сидоров'],
];
for (const [a, want] of T) {
  n++; const got = nbsp(a).replace(/ /g, '_');
  if (got !== want) { fail++; console.log('✗', JSON.stringify(a), '\n   получили:', got, '\n   ожидали: ', want); }
  n++; const again = nbsp(nbsp(a)); if (again !== nbsp(a)) { fail++; console.log('✗ не идемпотентно:', a); }
}
console.log(fail ? `ПРОВАЛ: ${fail} из ${n}` : `${n} из ${n} проверок пройдено`);
process.exit(fail ? 1 : 0);
